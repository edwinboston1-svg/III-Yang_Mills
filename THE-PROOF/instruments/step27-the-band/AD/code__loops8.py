"""loops8.py -- AD: the 2868 self-avoiding polygons of length 8 through the link (0, mu), mu = 0..3, each written from the link itself
(position 0, sign +1), as 8 x (x0, x1, x2, x3, dir, sign) relative to the link's site; the shape class = the sorted extent
(0,0,1,3) (0,0,2,2) (0,1,1,1) (0,1,1,2) (1,1,1,1) -> 0..4.  Writes loops8.h and checks the counts (24, 60, 48, 1440, 1296).
usage: python loops8.py"""
import os
from sap import closed_walks
here = os.path.dirname(os.path.abspath(__file__))
CLS = {(0, 0, 1, 3): 0, (0, 0, 2, 2): 1, (0, 1, 1, 1): 2, (0, 1, 1, 2): 3, (1, 1, 1, 1): 4}
ws = closed_walks(8)
assert len(ws) == 2868
tables = []
for mu in range(4):
    perm = list(range(4)); perm[0], perm[mu] = perm[mu], perm[0]        # swap axis 0 <-> mu
    ent = []
    for w in ws:
        pts = [tuple(p[perm[i]] for i in range(4)) for p in w]          # walk starting with +e_mu
        ext = tuple(sorted(max(p[i] for p in pts) - min(p[i] for p in pts) for i in range(4)))
        links = []
        for k in range(8):
            a, b = pts[k], pts[(k + 1) % 8]
            d = [i for i in range(4) if a[i] != b[i]][0]
            if b[d] > a[d]: links.append(a + (d, 1))
            else: links.append(b + (d, -1))
        assert links[0] == (0, 0, 0, 0, mu, 1)
        ent.append((CLS[ext], links))
    tables.append(ent)
from collections import Counter
print('class counts per direction:', [dict(Counter(e[0] for e in t)) for t in tables])
with open(os.path.join(here, 'loops8.h'), 'w') as h:
    h.write('/* generated by loops8.py: the 2868 length-8 polygons through (0, mu), link first */\n#define N8 2868\n#define NCL8 5\n')
    h.write('static const int L8CLS[4][N8] = {%s};\n' % ', '.join('{%s}' % ','.join(str(e[0]) for e in t) for t in tables))
    h.write('static const signed char L8[4][N8][8][6] = {%s};\n' % ', '.join(
        '{%s}' % ', '.join('{%s}' % ','.join('{%s}' % ','.join(str(v) for v in l) for l in e[1]) for e in t) for t in tables))
print('wrote loops8.h')
