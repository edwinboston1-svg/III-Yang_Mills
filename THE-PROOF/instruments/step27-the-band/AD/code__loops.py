"""loops.py -- AD: the loop family of the fitted coarse action, enumerated ONCE per geometric loop per site, with the counts checked
(plaquettes 6, rectangles 12, chairs 48, parallelograms 16 per site in 4D) and the per-link incidence (6, 18, 72, 24) checked.
A loop is (start offset, list of steps (dir, +-1)).  Writes loops.h for ymc.c and loops.json for the row computation.
usage: python loops.py"""
import itertools, json

def plaquettes():
    out = []
    for mu, nu in itertools.combinations(range(4), 2):
        out.append(((0, 0, 0, 0), [(mu, 1), (nu, 1), (mu, -1), (nu, -1)]))
    return out

def rectangles():
    out = []
    for mu in range(4):
        for nu in range(4):
            if nu == mu: continue
            out.append(((0, 0, 0, 0), [(mu, 1), (mu, 1), (nu, 1), (mu, -1), (mu, -1), (nu, -1)]))
    return out

def chairs():
    """two plaquettes in different planes sharing the link (y, nu), the shared link removed: from y + s1 mu: -s1 mu, +s2 rho, +nu, -s2 rho, +s1 mu, -nu"""
    out = []
    for nu in range(4):
        others = [d for d in range(4) if d != nu]
        for mu, rho in itertools.combinations(others, 2):
            for s1 in (1, -1):
                for s2 in (1, -1):
                    st = [0, 0, 0, 0]; st[mu] = s1
                    out.append((tuple(st), [(mu, -s1), (rho, s2), (nu, 1), (rho, -s2), (mu, s1), (nu, -1)]))
    return out

def parallelograms():
    """the 4 Petrie hexagons of each unit 3-cube at the site (one per body diagonal)"""
    out = []
    for axes in itertools.combinations(range(4), 3):
        verts = list(itertools.product((0, 1), repeat=3))
        for v in verts:
            if v[0] == 1: continue            # each diagonal once: v with first bit 0, partner the complement
            vb = tuple(1 - b for b in v)
            rest = [w for w in verts if w != v and w != vb]
            # walk the 6-cycle (adjacent = differ in one bit)
            cyc = [rest[0]]
            while len(cyc) < 6:
                cur = cyc[-1]
                nxt = [w for w in rest if w not in cyc and sum(a != b for a, b in zip(w, cur)) == 1]
                cyc.append(nxt[0])
            assert sum(a != b for a, b in zip(cyc[-1], cyc[0])) == 1
            steps = []
            for i in range(6):
                a, b = cyc[i], cyc[(i + 1) % 6]
                k = [j for j in range(3) if a[j] != b[j]][0]
                steps.append((axes[k], b[k] - a[k]))
            st = [0, 0, 0, 0]
            for j in range(3): st[axes[j]] = cyc[0][j]
            out.append((tuple(st), steps))
    return out

def links_of(loop, base=(0, 0, 0, 0)):
    st, steps = loop
    x = list(a + b for a, b in zip(base, st)); L = []
    for d, s in steps:
        if s > 0:
            L.append((tuple(x), d, 1)); x[d] += 1
        else:
            x[d] -= 1; L.append((tuple(x), d, -1))
    assert tuple(x) == tuple(a + b for a, b in zip(base, st)), 'not closed'
    return L

def canon(loop, base):
    return frozenset((l[0], l[1]) for l in links_of(loop, base))

def check(name, fam, per_site, per_link):
    assert len(fam) == per_site, (name, len(fam))
    # distinctness under translation: canonical link sets from a window of base sites
    seen = set(); W = range(-3, 4)
    for b in itertools.product(W, repeat=4):
        for lp in fam:
            c = canon(lp, b)
            assert c not in seen, ('duplicate', name)
            seen.add(c)
    # incidence of the link (0, mu=0)
    cnt = 0
    for b in itertools.product(W, repeat=4):
        for lp in fam:
            for (x, d, s) in links_of(lp, b):
                if x == (0, 0, 0, 0) and d == 0: cnt += 1
    assert cnt == per_link, (name, cnt, per_link)
    print('%-15s %3d per site, %3d per link: OK' % (name, len(fam), cnt))

fams = [('plaquette', plaquettes(), 6, 6), ('rectangle', rectangles(), 12, 18), ('chair', chairs(), 48, 72),
        ('parallelogram', parallelograms(), 16, 24)]
for nm, f, a, b in fams: check(nm, f, a, b)

with open('loops.h', 'w') as h:
    h.write('/* generated by loops.py: loop families of the fitted coarse action, one entry per geometric loop per site */\n')
    h.write('#define NFAM 4\nstatic const int FAM_N[NFAM] = {%s};\nstatic const int FAM_LEN[NFAM] = {4, 6, 6, 6};\n' % ', '.join(str(len(f)) for _, f, _, _ in fams))
    h.write('static const char *FAM_NAME[NFAM] = {"plaquette", "rectangle", "chair", "parallelogram"};\n')
    tot = sum(len(f) for _, f, _, _ in fams)
    h.write('#define NLOOPTOT %d\n' % tot)
    h.write('static const int LOOP_FAM[NLOOPTOT] = {%s};\n' % ', '.join(str(i) for i, (_, f, _, _) in enumerate(fams) for _ in f))
    h.write('static const int LOOP_ST[NLOOPTOT][4] = {%s};\n' % ', '.join('{%s}' % ','.join(map(str, lp[0])) for _, f, _, _ in fams for lp in f))
    h.write('static const int LOOP_STEP[NLOOPTOT][6][2] = {%s};\n' % ', '.join(
        '{%s}' % ','.join('{%d,%d}' % s for s in (lp[1] + [(0, 0)] * (6 - len(lp[1])))) for _, f, _, _ in fams for lp in f))
json.dump({nm: [[list(lp[0]), [list(s) for s in lp[1]]] for lp in f] for nm, f, _, _ in fams}, open('loops.json', 'w'))
print('wrote loops.h, loops.json; total loops per site', sum(len(f) for _, f, _, _ in fams))

# ---- incidence tables: for the link (0, mu), every (loop index, base offset, position, sign) whose loop contains it
allloops = [lp for _, f, _, _ in fams for lp in f]
inc = {mu: [] for mu in range(4)}
W = range(-3, 4)
for mu in range(4):
    for b in itertools.product(W, repeat=4):
        for li, lp in enumerate(allloops):
            for pos, (x, d, s) in enumerate(links_of(lp, b)):
                if x == (0, 0, 0, 0) and d == mu:
                    inc[mu].append((li, b, pos, s))
for mu in range(4):
    assert len(inc[mu]) == 120, len(inc[mu])
with open('loops.h', 'a') as h:
    h.write('#define NINC 120\n')
    h.write('static const int INC[4][NINC][7] = {%s};\n' % ', '.join(
        '{%s}' % ', '.join('{%d,%d,%d,%d,%d,%d,%d}' % (li, b[0], b[1], b[2], b[3], pos, s) for (li, b, pos, s) in inc[mu]) for mu in range(4)))
print('incidence: 120 loop occurrences per link direction, written')
